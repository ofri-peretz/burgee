/**
 * The SC8 run ledger: every head-to-head run in `.sdlc/intents/oxmutate/sc8/runs/`, valid or
 * void, and why. Rewrites `RUNS.md` beside the runs. Run it after adding a run's files.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gunzipSync } from 'node:zlib';

const here = join(dirname(fileURLToPath(import.meta.url)), '..', '.sdlc', 'intents', 'oxmutate', 'sc8');
const runs = join(here, 'runs');
const voids = JSON.parse(readFileSync(join(here, 'void.json'), 'utf8'));
/** A run's own result is a few MB at most; anything larger is not one of ours. */
const MAX_RESULT_BYTES = 64 * 1024 * 1024;
const ERROR_CHARS = 80;
const SECONDS_PER_MINUTE = 60;
/** Below this share of one-per-minute load samples, the machine slept and wall time is not run time. */
const MIN_SAMPLE_SHARE = 0.9;
/** Owner rule, 2026-11-02: the engines' mean loads must be within this factor to compare. */
const MAX_LOAD_RATIO = 1.5;
const json = (f) => (existsSync(f) ? JSON.parse(gunzipSync(readFileSync(f), { maxOutputLength: MAX_RESULT_BYTES }).toString('utf8')) : undefined);

const rows = readdirSync(runs).filter((f) => f.endsWith('.meta')).sort().map((f) => {
  const label = f.slice(0, -'.meta'.length);
  const meta = readFileSync(join(runs, f), 'utf8');
  const kv = Object.fromEntries([...meta.matchAll(/(\w+)=(\S*)/g)].map((m) => [m[1], m[2]]));
  const start = meta.match(/^start (\S+)/m)?.[1] ?? '';
  const wall = Number(meta.match(/^wall_s (\d+)/m)?.[1] ?? NaN);
  const loads = existsSync(join(runs, `${label}.loadlog`))
    ? readFileSync(join(runs, `${label}.loadlog`), 'utf8').trim().split('\n').filter(Boolean).map((l) => Number(l.replace(/[{}]/g, ' ').trim().split(/\s+/)[1]))
    : [];
  const meanLoad = loads.length ? loads.reduce((a, b) => a + b, 0) / loads.length : NaN;
  const ox = json(join(runs, `${label}.json.gz`));
  const st = json(join(runs, `${label}.result.json.gz`));
  const counts = ox?.counts ?? (st?.summary ? { Killed: st.summary.killed, Survived: st.summary.survived, Timeout: st.summary.timeout } : undefined);
  // Void when: listed in void.json (a cause found by hand), no wall time (never finished), the
  // engine reported no result, or fewer than 90% of the expected one-per-minute load samples
  // (the machine slept, so wall time is not run time).
  let why = voids[label];
  if (!why && Number.isNaN(wall)) why = 'did not finish';
  if (!why && st && !st.ok) why = `Stryker: ${String(st.error).slice(0, ERROR_CHARS)}`;
  if (!why && !ox && !st) why = 'no result file';
  const minutes = Math.floor(wall / SECONDS_PER_MINUTE);
  if (!why && loads.length < MIN_SAMPLE_SHARE * minutes) why = `machine slept: ${loads.length} load samples for ${minutes} min`;
  return { label, engine: kv.engine, pkg: kv.pkg, mode: kv.mode || '', start, wall, meanLoad, samples: loads.length, counts, why };
});

const fmt = (n, d = 0) => (Number.isFinite(n) ? n.toLocaleString('en-US', { maximumFractionDigits: d, minimumFractionDigits: d }) : '—');
const status = (r) => {
  if (!r.why) return 'valid';
  return r.why.startsWith('superseded') ? r.why : `void: ${r.why}`;
};
const c = (r) => (r.counts ? `${fmt(r.counts.Killed)} / ${fmt(r.counts.Timeout)} / ${fmt(r.counts.Survived)}` : '—');
const lines = [
  '# SC8 run ledger',
  '',
  'Generated by `node scripts/sc8-ledger.mjs` from `runs/`. Do not edit by hand; add a run\'s files to `runs/`',
  '(and a cause to `void.json` when one was found by hand), then regenerate. Harness: `harness/`.',
  '',
  '| Run | Engine | Package | Start (UTC) | Wall s | Mean load | Samples | Killed / Timeout / Survived | Status |',
  '| :-- | :-- | :-- | :-- | --: | --: | --: | :-- | :-- |',
  ...rows.map((r) => `| \`${r.label}\` | ${r.engine}${r.mode ? ` (${r.mode})` : ''} | ${r.pkg} | ${r.start} | ${fmt(r.wall)} | ${fmt(r.meanLoad, 1)} | ${r.samples} | ${c(r)} | ${status(r)} |`),
  '',
  '## Valid runs by package',
  '',
  'SC8 compares medians. A Stryker/oxmutate comparison counts only when the two engines\' mean loads',
  'are within 1.5x of each other (owner rule, 2026-11-02).',
  '',
];
const median = (xs) => { const s = [...xs].sort((a, b) => a - b); const m = s.length >> 1; return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2; };
for (const pkg of [...new Set(rows.map((r) => r.pkg))].sort()) {
  const ok = rows.filter((r) => r.pkg === pkg && !r.why);
  const S = ok.filter((r) => r.engine === 'stryker');
  const O = ok.filter((r) => r.engine === 'oxmutate');
  if (!S.length || !O.length) { lines.push(`- **${pkg}**: not comparable yet (${S.length} valid Stryker, ${O.length} valid oxmutate).`); continue; }
  const sm = median(S.map((r) => r.wall));
  const om = median(O.map((r) => r.wall));
  const sl = median(S.map((r) => r.meanLoad));
  const ol = median(O.map((r) => r.meanLoad));
  const ratio = Math.max(sl, ol) / Math.min(sl, ol);
  lines.push(`- **${pkg}**: Stryker median ${fmt(sm)} s (n=${S.length}, load ${fmt(sl, 1)}); oxmutate median ${fmt(om)} s (n=${O.length}, load ${fmt(ol, 1)}). oxmutate is ${om < sm ? `${fmt(sm / om, 2)}x faster` : `${fmt(om / sm, 2)}x slower`}. Load ratio ${fmt(ratio, 2)}x: ${ratio <= MAX_LOAD_RATIO ? 'comparable' : 'NOT comparable, repeat at matched load'}.`);
}
writeFileSync(join(here, 'RUNS.md'), `${lines.join('\n')}\n`);
