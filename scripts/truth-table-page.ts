/**
 * Generates seniority's truth-table page from the table the package exports (seniority R1,
 * criterion 2): one row per combination of the five sources, and the one that wins.
 *
 * The page is written from `TRUTH_TABLE`, which is generated from `ORDER`, which is what the
 * resolver reads. So the page cannot describe an order a run does not follow: reorder `ORDER`
 * and this page, `truth-table.test.ts` and burgee's `precedence-vectors.test.ts` all go red.
 * `scripts/truth-table-page.test.ts` is the lock that keeps the committed page current.
 *
 *   npx tsx scripts/truth-table-page.ts [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';

// eslint-disable-next-line import-next/no-relative-packages -- by path, never by name: the page is written from the source this checkout has, not from a dist/ an earlier build left
import { ORDER } from '../packages/seniority/src/precedence.js';
// eslint-disable-next-line import-next/no-relative-packages -- as above
import { TRUTH_TABLE } from '../packages/seniority/src/truth-table.js';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
export const PAGE = join(root, 'apps/docs-seniority/content/docs/guides/truth-table.md');

/** How each source reads as a column heading: `package` is a field in a file people know by name. */
const heading = (source: string): string => (source === 'package' ? '`package.json`' : `\`${source}\``);

export function render(): string {
  const rows = TRUTH_TABLE.map((row) => `| ${ORDER.map((s) => (row.set.includes(s) ? 'set' : '·')).join(' | ')} | ${row.winner === null ? 'nothing: the option is unset' : `**${heading(row.winner)}**`} |`);
  return [
    '---',
    'title: The truth table',
    `description: "Every combination of the ${String(ORDER.length)} sources seniority reads, and which one wins: ${String(TRUTH_TABLE.length)} rows generated from the exported TRUTH_TABLE, which is generated from ORDER, the array the resolver reads."`,
    '---',
    '',
    '<!-- Generated by scripts/truth-table-page.ts from seniority\'s TRUTH_TABLE. Do not edit; run `npm run truth-table:page`. -->',
    '',
    `The order is ${ORDER.map(heading).join(' > ')}: the first source that sets a value wins. The`,
    'table below is that sentence for every case, one row per combination of sources that set a',
    'value. `set` means the source set one; `·` means it did not.',
    '',
    `| ${ORDER.map(heading).join(' | ')} | wins |`,
    `| ${ORDER.map(() => ':-:').join(' | ')} | :-- |`,
    ...rows,
    '',
    'The same rows are exported as data, so a program, a test or a page can read them:',
    '',
    '```js',
    "import { TRUTH_TABLE } from 'seniority';",
    '',
    "TRUTH_TABLE.find((row) => row.set.join() === 'env,config').winner; // 'env'",
    '```',
    '',
    `\`TRUTH_TABLE\` is \`truthTable(ORDER)\`, and \`ORDER\` is the array \`resolve\` reads. The repository holds both`,
    'to `precedence-vectors.json`, in seniority\'s suite and through a real burgee program, so a',
    'change to the order has to change the vectors in the same diff.',
    '',
    'A plugin source slots between two of these by `rank` and never reorders them; see',
    '[Plugins](./plugins).',
    '',
  ].join('\n');
}

function main(): void {
  const want = render();
  let committed = '';
  try {
    committed = readFileSync(PAGE, 'utf8');
  } catch {
    committed = '';
  }
  if (process.argv.includes('--check')) {
    if (committed !== want) {
      process.stderr.write(`✖ ${PAGE} is not what TRUTH_TABLE generates — run \`npm run truth-table:page\`\n`);
      process.exit(1);
    }
    process.stdout.write('✓ the truth-table page matches TRUTH_TABLE\n');
    return;
  }
  writeFileSync(PAGE, want);
  process.stdout.write(`wrote ${PAGE}\n`);
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) main();
