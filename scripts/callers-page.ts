/**
 * callers-page.ts — renders `/docs/callers` from the caller matrix (`.sdlc/intents/caller-matrix/`, R4).
 *
 *   npx tsx scripts/callers-page.ts           # write apps/docs/content/docs/callers.mdx
 *   npx tsx scripts/callers-page.ts --check   # exit 1 when the committed page is not what the registry generates
 *
 * The registry is `examples/conformance/src/callers.ts`; this page is never edited by hand
 * (intent constraint 3). `scripts/callers-lock.test.ts` is what keeps the registry true.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

// eslint-disable-next-line import-next/no-relative-packages -- by path: the registry sits beside the conformance suite it indexes, a private workspace the root does not depend on
import { type Caller, CALLERS, type Cell, type Feature, FEATURES, MATRIX } from '../examples/conformance/src/callers';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const PAGE = join(ROOT, 'apps/docs/content/docs/callers.mdx');
const SOURCE = 'https://github.com/ofri-peretz/burgee/blob/main';

const callers = Object.keys(CALLERS) as Caller[];
const features = Object.keys(FEATURES) as Feature[];

/** A `|` inside a table cell ends the cell; escape it. */
const inCell = (s: string): string => s.replace(/\|/g, '\\|');

function mark(cell: Cell): string {
  if ('test' in cell) return '✅';
  if ('na' in cell) return 'n/a';
  return '❌ missing';
}

function detail(f: Feature, c: Caller, cell: Cell): string {
  if ('test' in cell) return `| ${f} | ${c} | ✅ [\`${cell.test}\`](${SOURCE}/${cell.test}) › “${inCell(cell.name)}” |`;
  if ('na' in cell) return `| ${f} | ${c} | n/a — ${inCell(cell.na)} |`;
  return `| ${f} | ${c} | ❌ missing — no test holds this cell yet |`;
}

function render(): string {
  const all = features.flatMap((f) => callers.map((c) => MATRIX[f][c]));
  const count = (kind: 'test' | 'na' | 'missing'): number => all.filter((cell) => kind in cell).length;
  return [
    '---',
    'title: Callers',
    'description: Every feature against every caller — a person, an agent, CI, a screen reader and another program — and the test that holds each cell.',
    '---',
    '',
    'Generated by `npm run callers:page` from `examples/conformance/src/callers.ts`.',
    'Do not edit by hand.',
    '',
    'Five callers arrive at a command, and each one is told apart by what it can observe — whether',
    'stdout is a terminal, the environment, the flags — never by guessing who is on the other end.',
    'Every feature has a cell per caller. A cell is held by a named test, does not apply (and says',
    'why, and that caller gets the plain static text), or is missing. A missing cell is a gap we',
    'publish, and the count of them may only fall.',
    '',
    `**${count('test')} held · ${count('na')} n/a · ${count('missing')} missing**, of ${all.length} cells.`,
    '',
    '## The callers',
    '',
    '| Caller | Who | Told apart by | Mode |',
    '| :--- | :--- | :--- | :--- |',
    ...callers.map((c) => `| ${c} | ${CALLERS[c].who} | ${inCell(CALLERS[c].inputs)} | \`${CALLERS[c].mode}\` |`),
    '',
    '## The matrix',
    '',
    `| Feature | Package | ${callers.join(' | ')} |`,
    `| :--- | :--- | ${callers.map(() => ':---:').join(' | ')} |`,
    ...features.map((f) => `| ${f} | ${FEATURES[f]} | ${callers.map((c) => mark(MATRIX[f][c])).join(' | ')} |`),
    '',
    '## Each cell',
    '',
    '| Feature | Caller | Held by |',
    '| :--- | :--- | :--- |',
    ...features.flatMap((f) => callers.map((c) => detail(f, c, MATRIX[f][c]))),
    '',
  ].join('\n');
}

function main(): void {
  const want = render();
  if (process.argv.includes('--check')) {
    // A page that does not exist is a page that differs.
    const committed = existsSync(PAGE) ? readFileSync(PAGE, 'utf8') : '';
    if (committed !== want) {
      process.stderr.write(`✖ ${PAGE} is not what the caller matrix generates — run \`npm run callers:page\`\n`);
      process.exitCode = 1;
      return;
    }
    process.stdout.write('✓ the callers page matches the caller matrix\n');
    return;
  }
  writeFileSync(PAGE, want);
  process.stdout.write(`wrote ${PAGE}\n`);
}

main();
