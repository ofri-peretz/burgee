/**
 * Z5, restated to a bench (`.sdlc/intents/burgee/spec.md` § Design gate 2026-10-25): what a
 * program of 250 commands costs to answer `--help` and `--schema`, beside one of 30.
 *
 * yargs #1005 asked whether a large CLI should precompute its manifest. burgee keeps the manifest
 * in memory and builds it at start-up (the in-memory half of Z5, held by
 * `examples/conformance/src/modularity.test.ts`), and the precompute opt-in was dropped
 * (D-20261025-burgee-umbrella-design-accepted) because nothing measured asked for it. This is the
 * measurement: if the 250-command reading is more than 3× the 30-command one, a precompute intent
 * is opened from that number — so 3× is the gate, and a red gate is that signal.
 *
 * Three things carried over from the cold-start rows, for the same reasons (`perf.ts`):
 *
 * - **The fixtures are generated, not committed** (the design gate's acceptance). One generator
 *   writes both sizes in the shape of `examples/demo-cli-large` — commands across five groups, a
 *   shared option set spread into each, one in ten loading its handler lazily from its own module
 *   — so the only thing that differs between the two programs is how many commands they declare.
 * - **Interleaved, paired rounds.** One round spawns all four (size × surface) once, rotating
 *   which goes first, and the gated number is the median of round *i*'s 250 over round *i*'s 30:
 *   a ratio of two spawns seconds apart, which the machine's own start-up cancels out of.
 * - **Proved before timed.** Each fixture's `--schema` must parse and list exactly the commands it
 *   was generated with, and `--help` must name the last of them; and neither surface may import a
 *   lazy handler, which announces itself on stderr when it loads. A fixture that stopped parsing
 *   would otherwise produce a beautiful number about nothing.
 */
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { type BenchRecord } from '../record.js';
import { spawnSync } from '../spawn.js';
import { median, p95, round } from '../stats.js';

const BENCH_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
/** Generated per run and gitignored (`benchmarks/.gitignore`: `.fixtures-*\/`). Under `benchmarks/` so `burgee` resolves as the other fixtures' does. */
export const SCALE_DIR = join(BENCH_ROOT, '.fixtures-scale');

/** The two sizes: the 30 of `examples/demo-cli-large`, and the 250 yargs #1005 names. */
export const SIZES = [30, 250] as const;
export const SURFACES = ['--help', '--schema'] as const;
export type Surface = (typeof SURFACES)[number];

/**
 * The ceiling on the paired 250 ÷ 30 ratio, for each surface: the decision's own number. Above
 * it, opening a precompute intent is what D-20261025-burgee-umbrella-design-accepted says to do,
 * so the gate going red is that signal and not a flaky runner — a ratio of two sizes timed in the
 * same rounds does not move with the machine. Proven red from 0 first; see
 * D-20261026-scale-bench-gate for the readings it was set against.
 */
export const SCALE_RATIO_CEILING = 3;

/** Four spawns a round, so a whole multiple of four gives every spawn each starting position equally often. */
const PER_ROUND = SIZES.length * SURFACES.length;
export const SCALE_ROUNDS = 24;
const GROUPS = ['Repository:', 'Packages:', 'Environments:', 'Reports:', 'Maintenance:'] as const;
/** One command in ten loads its handler on dispatch (M2), as three of `demo-cli-large`'s thirty do. */
const LAZY_EVERY = 10;
const RATIO_PLACES = 3;
const MS_PLACES = 2;

/** Three digits, so 250 names sort in order and a regex can tell them from burgee's own commands. */
const NAME_DIGITS = 3;
const name = (i: number): string => `cmd-${String(i + 1).padStart(NAME_DIGITS, '0')}`;
/** How much of a failing spawn's stderr goes into the error. */
const STDERR_EXCERPT = 200;

/** The program source for `commands` commands, in the shape of `examples/demo-cli-large`. */
export function programSource(commands: number): string {
  const lines = [
    `// Generated by benchmarks/axes/scale.ts — ${String(commands)} commands. Not committed; rewritten every run.`,
    `import { defineCommand, defineProgram, run, sharedOptions } from 'burgee';`,
    ``,
    `const common = sharedOptions('common', { verbose: { type: 'boolean', description: 'say more' }, dryRun: { type: 'boolean', description: 'show what would happen' } });`,
    `const commands = [`,
  ];
  for (let i = 0; i < commands; i++) {
    const group = GROUPS[i % GROUPS.length] as string;
    const head = `name: '${name(i)}', description: '${group.slice(0, -1)} command ${String(i + 1)}', group: '${group}', effects: 'read_only'`;
    const options = `options: { ...common, limit: { type: 'number', description: 'how many', default: 10 } }`;
    const body = i % LAZY_EVERY === LAZY_EVERY - 1 ? `load: () => import('./cmds/${name(i)}.mjs')` : `run: ({ options }) => ({ command: '${name(i)}', limit: options.limit })`;
    lines.push(`  defineCommand({ ${head}, ${options}, ${body} }),`);
  }
  lines.push(`];`, ``, `await run(defineProgram({ name: 'scale', version: '1.0.0', description: 'A ${String(commands)}-command program', commands }));`, ``);
  return lines.join('\n');
}

/** A lazy handler's module: it says so on stderr when it is imported, which help and schema must never cause. */
export function handlerSource(i: number): string {
  return `process.stderr.write('loaded ${name(i)}\\n');\nexport function run({ options }) {\n  return { command: '${name(i)}', limit: options.limit };\n}\n`;
}

/** Write both programs under `dir`; returns each size's entry file. */
export function writeFixtures(dir = SCALE_DIR): Map<number, string> {
  rmSync(dir, { recursive: true, force: true });
  const out = new Map<number, string>();
  for (const size of SIZES) {
    const at = join(dir, String(size));
    mkdirSync(join(at, 'cmds'), { recursive: true });
    for (let i = 0; i < size; i++) if (i % LAZY_EVERY === LAZY_EVERY - 1) writeFileSync(join(at, 'cmds', `${name(i)}.mjs`), handlerSource(i));
    const entry = join(at, 'cli.mjs');
    writeFileSync(entry, programSource(size));
    out.set(size, entry);
  }
  return out;
}

interface Spawned {
  ms: number;
  stdout: string;
  stderr: string;
  status: number | null;
}

// `NO_COLOR` so help prints the same bytes on a runner as on a laptop, as the colour rows do in `perf.ts`.
const ENV = { ...process.env, NO_COLOR: '1' };
/** A 250-command `--schema` is a few hundred kB; the default 1 MB buffer is too near for comfort. */
const MAX_BUFFER = 16 * 1024 * 1024;

function spawn(entry: string, surface: Surface): Spawned {
  const started = performance.now();
  const r = spawnSync(process.execPath, [entry, surface], { encoding: 'utf8', env: ENV, maxBuffer: MAX_BUFFER });
  return { ms: performance.now() - started, stdout: r.stdout, stderr: r.stderr, status: r.status };
}

/** Why `entry`'s answer to `surface` is not a `size`-command program's, or undefined when it is. */
export function answerProblem(size: number, surface: Surface, r: Pick<Spawned, 'stdout' | 'stderr' | 'status'>): string | undefined {
  if (r.status !== 0) return `exit ${String(r.status)}: ${r.stderr.slice(0, STDERR_EXCERPT)}`;
  if (r.stderr.includes('loaded ')) return `imported a lazy handler: ${r.stderr.trim()}`;
  if (surface === '--help') return r.stdout.includes(name(size - 1)) ? undefined : `--help does not name ${name(size - 1)}`;
  let commands: unknown;
  try {
    commands = (JSON.parse(r.stdout) as { commands?: unknown }).commands;
  } catch (e) {
    return `--schema did not parse: ${(e as Error).message}`;
  }
  // Only the generated ones: burgee adds its own `completion` command to every program.
  const count = Array.isArray(commands) ? commands.filter((c: { name?: unknown }) => /^cmd-\d{3}$/.test(String(c.name))).length : -1;
  return count === size ? undefined : `--schema lists ${String(count)} generated commands, not ${String(size)}`;
}

/** Before anything is timed, every size answers every surface as the program it was generated as. */
export function proveFixtures(entries: ReadonlyMap<number, string>): void {
  for (const [size, entry] of entries)
    for (const surface of SURFACES) {
      const problem = answerProblem(size, surface, spawn(entry, surface));
      if (problem !== undefined) throw new Error(`scale ${String(size)} ${surface}: ${problem}`);
    }
}

const key = (size: number, surface: Surface): string => `${String(size)} ${surface}`;
const PAIRS = SIZES.flatMap((size) => SURFACES.map((surface) => ({ size, surface })));

function timings(entries: ReadonlyMap<number, string>, rounds: number): Map<string, number[]> {
  const samples = new Map(PAIRS.map((p) => [key(p.size, p.surface), [] as number[]]));
  // One discarded round: the first spawn of each file pays for reading it off disk.
  for (let r = -1; r < rounds; r++)
    for (let i = 0; i < PAIRS.length; i++) {
      const { size, surface } = PAIRS[(i + Math.max(r, 0)) % PAIRS.length] as (typeof PAIRS)[number];
      const s = spawn(entries.get(size) as string, surface);
      const problem = answerProblem(size, surface, s);
      if (problem !== undefined) throw new Error(`scale ${String(size)} ${surface}: ${problem}`);
      if (r >= 0) samples.get(key(size, surface))?.push(s.ms);
    }
  return samples;
}

const range = (xs: readonly number[], places: number): string => `${String(round(Math.min(...xs), places))}–${String(round(Math.max(...xs), places))}`;

export function msRecord(size: number, surface: Surface, xs: number[]): BenchRecord {
  return {
    axis: 'perf',
    variant: `${String(size)} commands, ${surface}`,
    metric: 'scale-start-ms',
    unit: 'ms',
    samples: xs.length,
    median: round(median(xs), MS_PLACES),
    p95: round(p95(xs), MS_PLACES),
    note: `spawned \`node cli.mjs ${surface}\` over a generated ${String(size)}-command program; absolute ms are this machine's, the ratio row is the number`,
    detail: { commands: size, surface, range: range(xs, MS_PLACES) },
  };
}

export function ratioRecord(surface: Surface, large: number[], small: number[], gateMax = SCALE_RATIO_CEILING): BenchRecord {
  const [lo, hi] = SIZES;
  const paired = large.map((ms, i) => ms / (small[i] as number));
  return {
    axis: 'perf',
    variant: `${String(hi)} ÷ ${String(lo)} commands, ${surface}`,
    metric: 'scale-ratio',
    unit: 'ratio',
    samples: paired.length,
    median: round(median(paired), RATIO_PLACES),
    p95: round(p95(paired), RATIO_PLACES),
    gate: {
      max: gateMax,
      why: `Z5: above ${String(gateMax)}×, a ${String(hi)}-command program pays enough for its in-memory manifest that a precompute intent is opened from this number (D-20261025-burgee-umbrella-design-accepted)`,
    },
    note: `median of ${String(paired.length)} paired spawns, each round's ${String(hi)}-command ${surface} over the same round's ${String(lo)}`,
    detail: { range: range(paired, RATIO_PLACES) },
  };
}

/** A whole multiple of {@link PER_ROUND}, at most {@link SCALE_ROUNDS}: fewer when the caller asked the axis for fewer. */
export const scaleRounds = (asked: number): number => Math.max(PER_ROUND, Math.min(SCALE_ROUNDS, Math.ceil(asked / PER_ROUND) * PER_ROUND));

export function run(asked = SCALE_ROUNDS): BenchRecord[] {
  const entries = writeFixtures();
  proveFixtures(entries);
  const samples = timings(entries, scaleRounds(asked));
  const at = (size: number, surface: Surface): number[] => samples.get(key(size, surface)) as number[];
  const [lo, hi] = SIZES;
  return [...PAIRS.map(({ size, surface }) => msRecord(size, surface, at(size, surface))), ...SURFACES.map((surface) => ratioRecord(surface, at(hi, surface), at(lo, surface)))];
}

export const method = `Z5: two programs generated per run in the shape of examples/demo-cli-large (${String(SIZES[0])} and ${String(SIZES[1])} commands, five groups, a shared option set, one handler in ${String(LAZY_EVERY)} lazy), each spawned as \`node cli.mjs --help\` and \`--schema\` in ${String(SCALE_ROUNDS)} interleaved rounds after one discarded warm-up, every answer checked; the gated number is the paired ${String(SIZES[1])} ÷ ${String(SIZES[0])} ratio per surface, ceiling ${String(SCALE_RATIO_CEILING)}×.`;
