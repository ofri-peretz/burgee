/**
 * `REVIEW.md` from the checklist (triggerlist spec R3): one line per rule with a link to why it
 * exists, under a byte budget. Rules past a reviewer's limit drop silently, so over budget is an
 * error that names the rules to drop: the ones that fire least, by the counts `replz` reports.
 */
import { type Checklist, type Item } from './checklist.js';

/** The playbook's measured limit of the review tool this feeds: 150 KB. */
export const DEFAULT_BUDGET = 150_000;

export interface Compiled {
  readonly text: string;
  readonly bytes: number;
  readonly budget: number;
  /** Ids to drop to fit, lowest firing first; empty when it fits. */
  readonly drop: readonly string[];
}

const bytesOf = (text: string): number => Buffer.byteLength(text);

export const ruleLine = (item: Item): string => `- \`${item.id}\` ${item.question} ([why](${item.sources[0] as string}))`;

export const compile = (checklist: Checklist, source: string, budget: number, firings: Readonly<Record<string, number>> = {}): Compiled => {
  const lines = [
    '# REVIEW.md',
    '',
    `Generated by \`triggerlist compile\` from \`${source}\`. Do not edit it by hand: edit the checklist and compile again.`,
    'CI reads this file and the checklist from the base branch, so a pull request is always reviewed by the rules it did not write.',
    '',
    'The reviewer is shown only the rules whose triggers fire on the diff (`triggerlist match <base>`), each with the check that answers it. Every rule:',
    '',
    ...checklist.items.map(ruleLine),
    '',
  ];
  const text = lines.join('\n');
  const bytes = bytesOf(text);
  const drop: string[] = [];
  let excess = bytes - budget;
  // Least fired first; among equals, the later rule, which was added last.
  const order = checklist.items.map((item, index) => ({ item, index, fired: firings[item.id] ?? 0 })).sort((a, b) => a.fired - b.fired || b.index - a.index);
  for (const { item } of order) {
    if (excess <= 0) break;
    drop.push(item.id);
    excess -= bytesOf(`${ruleLine(item)}\n`);
  }
  return { text, bytes, budget, drop };
};
