import { describe, expect, it } from 'vitest';

import { type Checklist, type Item } from './checklist.js';
import { compile, DEFAULT_BUDGET, ruleLine } from './compile.js';

const item = (id: string): Item => ({ id, trigger: { paths: ['**'] }, question: `Is ${id} kept?`, check: 'c', sources: [`https://x/${id}`, 'second'] });
const LIST: Checklist = { gates: [], items: [item('a'), item('b'), item('c')] };

describe('compile', () => {
  it('writes one line per rule linking its first source, after a header naming the checklist', () => {
    const { text, drop, bytes, budget } = compile(LIST, '.sdlc/checklist.yaml', DEFAULT_BUDGET);
    expect(text).toBe(
      [
        '# REVIEW.md',
        '',
        'Generated by `triggerlist compile` from `.sdlc/checklist.yaml`. Do not edit it by hand: edit the checklist and compile again.',
        'CI reads this file and the checklist from the base branch, so a pull request is always reviewed by the rules it did not write.',
        '',
        'The reviewer is shown only the rules whose triggers fire on the diff (`triggerlist match <base>`), each with the check that answers it. Every rule:',
        '',
        '- `a` Is a kept? ([why](https://x/a))',
        '- `b` Is b kept? ([why](https://x/b))',
        '- `c` Is c kept? ([why](https://x/c))',
        '',
      ].join('\n'),
    );
    expect(drop).toEqual([]);
    expect(bytes).toBe(Buffer.byteLength(text));
    expect(budget).toBe(150_000);
  });

  it('counts bytes, not characters', () => {
    const { bytes, text } = compile({ gates: [], items: [{ ...item('a'), question: 'é' }] }, 's', DEFAULT_BUDGET);
    expect(bytes).toBe(text.length + 1);
  });

  it('fits exactly at the budget and drops nothing', () => {
    const { bytes } = compile(LIST, 's', DEFAULT_BUDGET);
    expect(compile(LIST, 's', bytes).drop).toEqual([]);
  });

  it('over budget, names the least-fired rules to drop, the later rule first among equals, until it fits', () => {
    const { bytes } = compile(LIST, 's', DEFAULT_BUDGET);
    const line = Buffer.byteLength(`${ruleLine(item('a'))}\n`);
    expect(compile(LIST, 's', bytes - 1).drop).toEqual(['c']);
    expect(compile(LIST, 's', bytes - line).drop).toEqual(['c']);
    expect(compile(LIST, 's', bytes - line - 1).drop).toEqual(['c', 'b']);
    expect(compile(LIST, 's', bytes - 1, { c: 5, b: 2 }).drop).toEqual(['a']);
    expect(compile(LIST, 's', bytes - line - 1, { c: 5, a: 1 }).drop).toEqual(['b', 'a']);
    // An item with no count has fired zero times: no fewer than one counted at zero.
    expect(compile(LIST, 's', bytes - 1, { a: 0 }).drop).toEqual(['c']);
    expect(compile(LIST, 's', bytes - 1, { b: 0.5 }).drop).toEqual(['c']);
  });
});
