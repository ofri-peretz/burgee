/**
 * Authored schemas of every kind, by name: `emit-type.test.ts` writes the type `typeOf` gives each
 * beside the type `Infer` gives it, and has `tsc` hold the two to each other.
 */

interface Tree {
  readonly name: string;
  readonly kids: Tree[];
}

const Tree: Schema<Tree> = object({ name: string(), kids: array(lazy(() => Tree)) });

class Point {
  readonly x = 0;
}

