/**
 * Writes `src/yargs/y18n-locales.ts`, the part of `locales/` that `burgee/yargs` carries in its
 * module graph rather than reading from disk (A-20261028-yargs-locale-read-at-runtime,
 * `yargs-compat` X11): the names of the locales it ships, and English.
 *
 * `locales/*.json` stay the one source. The output is committed and `--check` compares it with a
 * fresh render in the package's `build`, and `locales-embedded.test.ts` compares its values with
 * `locales/`, so a locale added, removed or edited without re-running this fails rather than
 * drifts.
 *
 * **English keeps only the entries that are not their own key.** y18n answers a key it has no
 * entry for with the key itself (`table[str] || str`, and `__n` with the singular or plural it was
 * handed), so an entry `"Commands:": "Commands:"` prints exactly what no entry prints. What is
 * left is the six plural forms and `Implications failed:`, the one message yargs rewords.
 *
 * No `en_*.json` may ship: English is served without asking the disk whether a more specific
 * file exists, which is right only while none does.
 *
 *   node scripts/generate-yargs-locales.mjs          # writes the module
 *   node scripts/generate-yargs-locales.mjs --check  # exits 1 if the committed module is stale
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const LOCALES = new URL('../locales/', import.meta.url);
const TARGET = new URL('../src/yargs/y18n-locales.ts', import.meta.url);

const shipped = readdirSync(LOCALES)
  .filter((name) => name.endsWith('.json'))
  .map((name) => name.slice(0, -'.json'.length))
  .sort();
const regional = shipped.filter((name) => name.startsWith('en_'));
if (regional.length > 0) throw new Error(`locales/ ships ${regional.join(', ')}: English is served from the module graph, so a regional English file would never be read`);

const english = JSON.parse(readFileSync(new URL('en.json', LOCALES), 'utf8'));
const kept = Object.entries(english).filter(([key, value]) => value !== key);

/** A string as a single-quoted literal, as the rest of the source writes them. */
const quote = (s) => `'${s.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
/** A translation: a string, or y18n's plural pair. */
const literal = (value) => (typeof value === 'string' ? quote(value) : `{ one: ${quote(value.one)}, other: ${quote(value.other)} }`);

const text = `/**
 * Generated by \`scripts/generate-yargs-locales.mjs\` from \`locales/*.json\`. Do not edit: change
 * the JSON and re-run it. \`--check\` fails the build on a stale copy.
 *
 * What \`burgee/yargs\` speaks without reading a file (\`yargs-compat\` X11): English, and the
 * names of the locales it can read from \`locales/\` when one is asked for.
 */

/** The locales \`locales/\` ships, by file name. Any other locale is its keys, as on y18n. */
export const SHIPPED: readonly string[] = [${shipped.map(quote).join(', ')}];

/** \`locales/en.json\` less the entries that are their own key, which y18n prints unchanged. */
export const EN: Readonly<Record<string, string | Readonly<{ one: string; other: string }>>> = {
${kept.map(([key, value]) => `  ${quote(key)}: ${literal(value)},`).join('\n')}
};
`;

if (process.argv.includes('--check')) {
  if (readFileSync(TARGET, 'utf8') !== text) {
    process.stderr.write('src/yargs/y18n-locales.ts is not what locales/ generates.\nRun: node scripts/generate-yargs-locales.mjs\n');
    process.exitCode = 1;
  } else {
    process.stdout.write(`src/yargs/y18n-locales.ts is current: ${shipped.length} locales, ${kept.length} English entries\n`);
  }
} else {
  writeFileSync(TARGET, text);
  process.stdout.write(`wrote src/yargs/y18n-locales.ts: ${shipped.length} locales, ${kept.length} English entries\n`);
}
