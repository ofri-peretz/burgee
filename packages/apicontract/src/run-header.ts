/**
 * The generated header (apicontract-gen-command R6): one comment line in the target language that
 * says the file is generated, names the command that regenerates it, and carries the sha256 of the
 * body below it, truncated to 12 hex digits. Recomputing that hash is how a hand edit is found.
 *
 * Generators return bodies only; this is the one place a header is written or read. A language
 * without comments (JSON) gets no header, and its hash is recorded in `apicontract.map.json`.
 */
import { createHash } from 'node:crypto';

const DIGITS = 12;

/** The sha256 of a body, as 12 hex digits: enough to tell an edit, short enough to read. */
export const digest = (body: string): string => createHash('sha256').update(body).digest('hex').slice(0, DIGITS);

const SLASHES = ['// ', ''] as const;
const HASH = ['# ', ''] as const;
const MARKUP = ['<!-- ', ' -->'] as const;

/** How each extension opens and closes a line comment. An extension not listed gets no header. */
const COMMENTS: ReadonlyMap<string, readonly [string, string]> = new Map<string, readonly [string, string]>([
  ['ts', SLASHES],
  ['tsx', SLASHES],
  ['mts', SLASHES],
  ['cts', SLASHES],
  ['js', SLASHES],
  ['jsx', SLASHES],
  ['mjs', SLASHES],
  ['cjs', SLASHES],
  ['yaml', HASH],
  ['yml', HASH],
  ['md', MARKUP],
]);

const extension = (path: string): string => path.slice(path.lastIndexOf('.') + 1);

/** The header line for a file, or `undefined` when its language has no comments. */
export const headerLine = (path: string, body: string, command: string): string | undefined => {
  const comment = COMMENTS.get(extension(path));
  if (comment === undefined) return undefined;
  return `${comment[0]}generated by apicontract — do not edit; run \`${command}\` (sha256:${digest(body)})${comment[1]}`;
};

/** The bytes to write: the header line, then the body. */
export const withHeader = (path: string, body: string, command: string): string => {
  const line = headerLine(path, body, command);
  return line === undefined ? body : `${line}\n${body}`;
};

const HEADER = /^(?:\/\/|#|<!--) generated by apicontract — do not edit; run `[^`\n]+` \(sha256:([\da-f]{12})\)(?: -->)?\n/u;

/** The hash a file's header declares and the body under it, or `undefined` when it has no header. */
export const readHeader = (content: string): { hash: string; body: string } | undefined => {
  const match = HEADER.exec(content);
  if (match === null) return undefined;
  return { hash: match[1] as string, body: content.slice(match[0].length) };
};
