describe('scanDiscriminators', () => {
  it('finds declared and inherited discriminators, and writes mapped values into the document', () => {
    const document = {
      components: {
        schemas: {
          Pet: { oneOf: [{ $ref: '#/components/schemas/Cat' }], discriminator: { propertyName: 'kind', mapping: { cat: '#/components/schemas/Cat' } } },
          Cat: { type: 'object' },
          Base: { discriminator: { propertyName: 'type' } },
          Child: { allOf: [{ $ref: '#/components/schemas/Base' }] },
        },
      },
    };
    expect(scanDiscriminators(document)).toEqual({
      objects: {
        '#/components/schemas/Pet': { propertyName: 'kind', mapping: { cat: '#/components/schemas/Cat' } },
        '#/components/schemas/Base': { propertyName: 'type' },
        '#/components/schemas/Child': { propertyName: 'type' },
      },
      refsHandled: ['#/components/schemas/Cat'],
    });
    expect(document.components.schemas.Cat).toEqual({
      type: 'object',
      required: ['kind'],
      properties: { kind: { type: 'string', enum: ['cat'], description: 'discriminator enum property added by openapi-typescript' } },
    });
  });

  it('writes a property called `__proto__` as an own member', () => {
    const document = {
      Pet: { oneOf: [{ $ref: '#/Cat' }], discriminator: { propertyName: '__proto__' } },
      Cat: { type: 'object' },
    };
    scanDiscriminators(document);
    expect(Object.keys((document.Cat as { properties?: object }).properties ?? {})).toEqual(['__proto__']);
    expect(Object.getPrototypeOf(document.Cat)).toBe(Object.prototype);
  });
});
