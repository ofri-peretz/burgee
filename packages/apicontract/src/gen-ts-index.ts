/** One Operation Object: its `parameters`, `requestBody` and `responses` members. */
export const transformOperationObject = (operation: unknown, options: TransformOptions): string =>
  printFile(operationMembers(operation, options));

/** One Request Body Object. */
export const transformRequestBodyObject = (requestBody: unknown, options: TransformOptions): string =>
  printFile([requestBodyType(requestBody, options)]);

/** One Response Object. */
export const transformResponseObject = (response: unknown, options: TransformOptions): string =>
  printFile([responseType(response, options)]);

/** One Header Object. */
