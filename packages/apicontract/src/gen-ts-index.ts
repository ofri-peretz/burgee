/**
 * TypeScript types from an OpenAPI 3.x document, byte for byte what openapi-typescript 7 prints,
 * without the TypeScript compiler: the types are written as text. Nothing here imports
 * `typescript`, so it runs the same under TypeScript 7, which ships no compiler API.
 *
 * Each `transform*` function takes what upstream's function of the same name takes and returns the
 * string upstream's `astToString` gives for its result. Local `#/…` references only: a document
 * split over files has to be bundled first.
 */
