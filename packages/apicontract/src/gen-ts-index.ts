/** The `ApiPaths` enum of a Paths Object. */
export const makeApiPathsEnum = (paths: unknown): string => printFile([pathsEnum(paths)]);

/** The whole file for a document, under a context the caller built: discriminators are not scanned here. */
export const transformSchema = (root: unknown, ctx: Context): string => printFile(documentStatements(root, ctx));

/**
 * The whole file for a parsed OpenAPI 3.x document: upstream's `astToString(await openapiTS(…))`.
 * The document is not changed.
 */
export const generate = (root: unknown, options: GenerateOptions = {}): string => {
  if (!isDict(root)) {
    throw new GenerateError('Expected a parsed OpenAPI document, an object.', 'parse the JSON or YAML first and pass the result');
  }
  checkOptions(options);
  checkVersion(root);
  // Discriminators are written into the schemas they map to, so the transforms read a copy.
  const copy = structuredClone(root);
  // Upstream's bundler gives every document a Components Object, so the root is always printed in full.
  copy.components ||= {};
  const ctx = createContext(copy, options, scanDiscriminators(copy));
  return printFile(documentStatements(copy, ctx));
};

