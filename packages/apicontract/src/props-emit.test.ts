import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import fc from 'fast-check';
import { parse as parseYaml } from 'seniority/yaml';
import { describe, expect, it } from 'vitest';

import { scratchDirs } from './__fixtures__/run/scratch-dir.js';
import { type Contract } from './core/model.js';
import { builtinAdapters } from './inputs.js';
import { emitArbitraries } from './props-emit.js';
import { draftOf, rooted, validatorJudge } from './props-judge.js';

const makeDir = scratchDirs();

interface Emitted {
  readonly arbitraries: Record<string, fc.Arbitrary<unknown>>;
  readonly notGenerated: { key: string; keyword: string }[];
}

/** The module `emitArbitraries` writes, imported as a consumer's test would, with fast-check resolved from here. */
const load = async (contract: Contract): Promise<Emitted> => {
  const { text } = emitArbitraries(contract, 'fixture');
  const file = join(makeDir('apicontract-props-emit-'), 'arbitraries.mjs');
  writeFileSync(file, text.replace("'fast-check'", JSON.stringify(import.meta.resolve('fast-check'))));
  // eslint-disable-next-line node-security/no-dynamic-dependency-loading -- the point of the test: the module as written to disk, loaded as a consumer's test loads it
  return (await import(file)) as Emitted;
};

const single = (schema: unknown, document: Record<string, unknown> = {}): Contract => ({
  format: 'jsonschema',
  document,
  operations: [{ id: 'op', source: '#', payloads: [{ name: 'body', direction: 'request', schema: schema as Contract['operations'][number]['payloads'][number]['schema'], required: true }] }],
});

/** Every sample of each arbitrary that holds to all its keywords passes the validator. */
const valid = async (contract: Contract): Promise<Emitted> => {
  const module = await load(contract);
  const loose = new Set(module.notGenerated.map((entry) => entry.key));
  for (const operation of contract.operations) {
    for (const payload of operation.payloads) {
      const key = `${operation.id} ${payload.name}`;
      if (payload.schema === false || loose.has(key)) continue;
      const judge = validatorJudge(rooted(payload.schema, contract.document), draftOf(contract));
      for (const value of fc.sample(module.arbitraries[key] as fc.Arbitrary<unknown>, { numRuns: 100, seed: 1 })) expect(judge.paths(value), `${key} ${JSON.stringify(value)}`).toEqual([]);
    }
  }
  return module;
};

/** The line `schema`'s arbitrary is written on. */
const line = (schema: unknown, document: Record<string, unknown> = {}): string | undefined => emitArbitraries(single(schema, document), 'x').text.split('\n').find((text) => text.startsWith('  "op body": '));

describe('emitArbitraries', () => {
  it('writes a module whose arbitraries make values the validator accepts, from a real contract', async () => {
    const document = parseYaml(readFileSync(fileURLToPath(new URL('__fixtures__/props/shop-new.yaml', import.meta.url)), 'utf8'));
    const contract = (Object.values(builtinAdapters).find((adapter) => adapter.detect(document)) as (typeof builtinAdapters)['openapi']).read(document);
    const module = await valid(contract);
    expect(Object.keys(module.arbitraries).sort()).toEqual([
      '#/components/schemas/Line',
      '#/components/schemas/NewOrder',
      '#/components/schemas/Order',
      'getOrder param:path:id',
      'getOrder response:200:application/json',
      'placeOrder body:application/json',
      'placeOrder response:201:application/json',
    ]);
    expect(module.notGenerated).toEqual([]);
    expect(emitArbitraries(contract, 'shop').text).toMatch(/^\/\/ Generated by `contractdiff props --emit` from shop\./);
    expect(emitArbitraries(contract, 'shop').count).toBe(7);
  });

  it.each([
    ['numbers', { type: 'object', required: ['a', 'b', 'c', 'd', 'e'], properties: { a: { type: 'integer', minimum: -2, exclusiveMaximum: 9 }, b: { type: 'integer', multipleOf: 5, exclusiveMinimum: 0, maximum: 30 }, c: { type: 'number', exclusiveMinimum: 0, maximum: 1 }, d: { type: 'number' }, e: { type: 'integer' } } }],
    ['strings and formats', { type: 'array', prefixItems: ['date', 'date-time', 'time', 'duration', 'email', 'hostname', 'ipv4', 'ipv6', 'uuid', 'regex', 'byte'].map((format) => ({ type: 'string', format })), items: false, minItems: 11 }],
    ['lengths', { type: 'object', required: ['s', 'a'], properties: { s: { type: 'string', minLength: 2, maxLength: 4 }, a: { type: 'array', items: { type: 'boolean' }, minItems: 1, maxItems: 3 } } }],
    ['a tuple with a rest', { type: 'array', prefixItems: [{ const: 'x' }, { type: 'integer' }], items: { type: 'string' }, minItems: 1, maxItems: 4 }],
    ['a tuple with an open rest', { type: 'array', prefixItems: [{ const: 'x' }], minItems: 3 }],
    ['a tuple with no room for a rest', { type: 'array', prefixItems: [{ const: 'x' }], items: { type: 'string' }, maxItems: 1 }],
    ['lists and unions', { anyOf: [{ enum: ['a', 'b'] }, { const: { k: [1] } }, { type: ['null', 'boolean'] }] }],
    ['an object with a required property it does not name', { type: 'object', required: ['n'], properties: {}, additionalProperties: { const: 1 } }],
    ['anything', true],
    ['an empty schema', {}],
  ])('%s', async (_name, schema) => {
    await valid(single(schema));
  });

  it('holds to OpenAPI 3.0 bounds and nullable', async () => {
    const schema = { type: 'integer', nullable: true, minimum: 1, exclusiveMinimum: true, maximum: 3, exclusiveMaximum: true };
    const module = await valid(single(schema, { openapi: '3.0.3' }));
    expect(new Set(fc.sample(module.arbitraries['op body'] as fc.Arbitrary<unknown>, { numRuns: 200, seed: 2 }))).toEqual(new Set([2, null]));
  });

  it('ties references, including one that names itself, and a reference behind a reference', async () => {
    const document = { $defs: { Tree: { type: 'object', required: ['v'], properties: { v: { type: 'integer' }, kids: { type: 'array', maxItems: 2, items: { $ref: '#/$defs/Tree' } } } }, Alias: { $ref: '#/$defs/Tree' } } };
    const module = await valid(single({ $ref: '#/$defs/Alias' }, document));
    expect(Object.keys(module.arbitraries).sort()).toEqual(['#/$defs/Alias', '#/$defs/Tree', 'op body']);
  });

  it('lists every keyword an arbitrary does not hold to, and passes looseness along references', async () => {
    const document = { $defs: { Code: { type: 'string', pattern: '^[A-Z]+$' }, Wrap: { type: 'object', properties: { code: { $ref: '#/$defs/Code' } } } } };
    const contract: Contract = {
      format: 'jsonschema',
      document,
      operations: [
        {
          id: 'op',
          source: '#',
          payloads: [
            { name: 'wrapped', direction: 'request', schema: { $ref: '#/$defs/Wrap' }, required: true },
            { name: 'loose', direction: 'request', schema: { type: 'object', not: { required: ['x'] }, if: true, oneOf: [{ type: 'object' }], unevaluatedProperties: false }, required: true },
            { name: 'objects', direction: 'request', schema: { type: 'object', propertyNames: { maxLength: 3 }, minProperties: 1, patternProperties: { '^a': true } }, required: true },
            { name: 'arrays', direction: 'request', schema: { type: 'array', uniqueItems: true, contains: { const: 1 } }, required: true },
            { name: 'strings', direction: 'request', schema: { type: 'string', format: 'color' }, required: true },
            { name: 'merged', direction: 'request', schema: { allOf: [{ type: 'string' }, { maxLength: 2 }] }, required: true },
            { name: 'empty-merge', direction: 'request', schema: { allOf: [] }, required: true },
            { name: 'beside', direction: 'request', schema: { type: 'string', anyOf: [{ maxLength: 1 }] }, required: true },
            { name: 'refsibling', direction: 'request', schema: { $ref: '#/$defs/Code', maxLength: 2 }, required: true },
            { name: 'missing', direction: 'request', schema: { $ref: '#/$defs/Nowhere' }, required: true },
            { name: 'never', direction: 'response', schema: false, required: true },
            { name: 'unknown-type', direction: 'request', schema: { type: 'thing' }, required: true },
            { name: 'nothing', direction: 'request', schema: 'not a schema' as unknown as boolean, required: true },
          ],
        },
      ],
    };
    const module = await load(contract);
    const rows = module.notGenerated.map((entry) => `${entry.key}: ${entry.keyword}`);
    expect(rows).toEqual([
      'op wrapped: via #/$defs/Code',
      'op loose: if',
      'op loose: not',
      'op loose: oneOf',
      'op loose: oneOf-siblings',
      'op loose: unevaluatedProperties',
      'op objects: minProperties',
      'op objects: patternProperties',
      'op objects: propertyNames',
      'op arrays: contains',
      'op arrays: uniqueItems',
      'op strings: format:color',
      'op merged: allOf',
      'op empty-merge: allOf',
      'op beside: anyOf-siblings',
      'op refsibling: $ref-siblings',
      'op refsibling: via #/$defs/Code',
      'op missing: $ref',
      'op unknown-type: type:thing',
      'op nothing: false',
      '#/$defs/Wrap: via #/$defs/Code',
      '#/$defs/Code: pattern',
    ]);
    expect('op never' in module.arbitraries).toBe(false);
    expect(fc.sample(module.arbitraries['op nothing'] as fc.Arbitrary<unknown>, { numRuns: 1 })).toEqual([undefined]);
  });
  it.each([
    ["fc.integer()", { type: 'integer' }],
    ["fc.integer({ min: -2, max: 8 })", { type: 'integer', minimum: -2, exclusiveMaximum: 9 }],
    ["fc.integer({ min: 1, max: 6 }).map((n) => n * 5)", { type: 'integer', multipleOf: 5, exclusiveMinimum: 0, maximum: 30 }],
    ["fc.integer({ min: 2 }).map((n) => n * 5)", { type: 'integer', multipleOf: 5, minimum: 7 }],
    ["fc.integer({ min: 2 })", { type: 'integer', multipleOf: 1.5, minimum: 2 }],
    ["fc.double({ noNaN: true, noDefaultInfinity: true }).map((n) => n + 0)", { type: 'number' }],
    ["fc.double({ min: 0, max: 1, minExcluded: true, noNaN: true, noDefaultInfinity: true }).map((n) => n + 0)", { type: 'number', exclusiveMinimum: 0, maximum: 1 }],
    ["fc.double({ min: 0, max: 1, maxExcluded: true, noNaN: true, noDefaultInfinity: true }).map((n) => n + 0)", { type: 'number', minimum: 0, exclusiveMaximum: 1 }],
    ["fc.string()", { type: 'string' }],
    ["fc.string({ minLength: 2, maxLength: 4 })", { type: 'string', minLength: 2, maxLength: 4 }],
    ["fc.array(fc.boolean(), {})", { type: 'array', items: { type: 'boolean' } }],
    ["fc.array(fc.boolean(), { minLength: 1, maxLength: 3 })", { type: 'array', items: { type: 'boolean' }, minItems: 1, maxItems: 3 }],
    ["fc.tuple(fc.tuple(fc.constant(\"x\"), fc.integer()), fc.array(fc.string(), { maxLength: 2 }), fc.integer({ min: 1, max: 2 })).map(([head, tail, cut]) => (cut < head.length ? head.slice(0, cut) : [...head, ...tail]))", { type: 'array', prefixItems: [{ const: 'x' }, { type: 'integer' }], items: { type: 'string' }, minItems: 1, maxItems: 4 }],
    ["fc.tuple(fc.tuple(fc.constant(\"x\")), fc.array(fc.jsonValue(), { minLength: 2 }), fc.integer({ min: 1, max: 1 })).map(([head, tail, cut]) => (cut < head.length ? head.slice(0, cut) : [...head, ...tail]))", { type: 'array', prefixItems: [{ const: 'x' }], minItems: 3 }],
    ["fc.tuple(fc.tuple(fc.constant(\"x\")), fc.constant([]), fc.integer({ min: 0, max: 1 })).map(([head, tail, cut]) => (cut < head.length ? head.slice(0, cut) : [...head, ...tail]))", { type: 'array', prefixItems: [{ const: 'x' }], items: false }],
    ["fc.tuple(fc.tuple(fc.constant(\"x\")), fc.constant([]), fc.integer({ min: 0, max: 1 })).map(([head, tail, cut]) => (cut < head.length ? head.slice(0, cut) : [...head, ...tail]))", { type: 'array', prefixItems: [{ const: 'x' }], items: { type: 'string' }, maxItems: 1 }],
    ["fc.tuple(fc.tuple(fc.constant(\"x\"), fc.constant(\"y\")), fc.constant([]), fc.integer({ min: 1, max: 1 })).map(([head, tail, cut]) => (cut < head.length ? head.slice(0, cut) : [...head, ...tail]))", { type: 'array', prefixItems: [{ const: 'x' }, { const: 'y' }], items: { type: 'string' }, minItems: 1, maxItems: 1 }],
    ["fc.record({ \"a\": fc.constant(null) }, { requiredKeys: [] })", { type: 'object', properties: { a: { type: 'null' } } }],
    ["fc.record({ \"a\": fc.constant(null), \"n\": fc.jsonValue() }, { requiredKeys: [\"a\",\"n\"] })", { type: 'object', required: ['a', 'n'], properties: { a: { type: 'null' } } }],
    ["fc.record({ \"n\": fc.constant(1) }, { requiredKeys: [\"n\"] })", { type: 'object', required: ['n'], additionalProperties: { const: 1 } }],
    ["fc.oneof(fc.constant(null), fc.boolean())", { type: ['null', 'boolean'] }],
    ["fc.boolean()", { anyOf: [], type: 'boolean' }],
    ["fc.string()", { allOf: [{ type: 'string' }, { maxLength: 2 }] }],
  ])('writes %s', (expression, schema) => {
    const line = emitArbitraries(single(schema), 'x').text.split('\n').find((text) => text.startsWith('  "op body": '));
    expect(line).toBe(`  "op body": ${expression},`);
  });

  it('leaves out an excluded end with no bound, and a length that is not a number', () => {
    expect(line({ type: 'number', exclusiveMinimum: true, exclusiveMaximum: true }, { openapi: '3.0.3' })).toBe('  "op body": fc.double({ noNaN: true, noDefaultInfinity: true }).map((n) => n + 0),');
    expect(line({ type: 'array', maxItems: 'x' })).toBe('  "op body": fc.array(fc.jsonValue(), {}),');
  });

  it('writes the whole module around the arbitraries', () => {
    expect(emitArbitraries(single({ type: 'null' }), 'c.yaml').text).toBe(
      [
        '// Generated by `contractdiff props --emit` from c.yaml. Do not edit: run it again.',
        '// One fast-check arbitrary per payload (`<operation> <payload>`) and per referenced schema.',
        "import fc from 'fast-check';",
        '',
        'export const arbitraries = fc.letrec((tie) => ({',
        '  "op body": fc.constant(null),',
        '}));',
        '',
        '/** Keywords an arbitrary above does not hold to: filter its values with your validator. */',
        'export const notGenerated = [];',
        '',
      ].join('\n'),
    );
  });

  it('names what it does not hold to, and nothing it does', async () => {
    const document = { $defs: { Tree: { type: 'object', propertyNames: { maxLength: 3 }, properties: { kids: { type: 'array', items: { $ref: '#/$defs/Tree' } } } } } };
    const rows = async (schema: unknown, doc: Record<string, unknown> = document): Promise<string[]> => (await load(single(schema, doc))).notGenerated.map((entry) => `${entry.key}: ${entry.keyword}`);
    expect(await rows({ $ref: '#/$defs/Tree' })).toEqual(['op body: via #/$defs/Tree', '#/$defs/Tree: propertyNames']);
    expect(await rows({ anyOf: [{ type: 'string' }, { type: 'null' }] })).toEqual([]);
    expect(await rows({ $ref: '#/$defs/Tree', description: 'd' }, { ...document, openapi: '3.0.3' })).toEqual(['op body: via #/$defs/Tree', '#/$defs/Tree: propertyNames']);
    expect(await rows({ type: 'object', dependentRequired: {}, dependentSchemas: {}, dependencies: {}, maxProperties: 2 })).toEqual(['op body: dependencies', 'op body: dependentRequired', 'op body: dependentSchemas', 'op body: maxProperties']);
    expect(await rows({ type: 'array', unevaluatedItems: false })).toEqual(['op body: unevaluatedItems']);
    expect(await rows({ type: ['integer', 'number'], multipleOf: 0.5 })).toEqual(['op body: multipleOf']);
    expect(await rows({ type: 'integer', multipleOf: 3 })).toEqual([]);
    expect(await rows({ type: 'integer', multipleOf: 1 })).toEqual([]);
    expect(await rows({ type: 'integer', multipleOf: 0.5 })).toEqual(['op body: multipleOf']);
    expect(await rows({ type: 'number', multipleOf: 2 })).toEqual(['op body: multipleOf']);
  });
});
