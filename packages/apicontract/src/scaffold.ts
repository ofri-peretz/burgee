/**
 * `apicontract plugin new <name>` (apicontract-kit R3): the files of a plugin that passes the
 * conformance suite as generated, as plain strings. Every file is the user's (`owner: 'user'`):
 * written once, never rewritten, which is what makes a second `plugin new` safe.
 *
 * The plugin and its test import from `apicontract/testing` only, and the test runs under
 * `node:test`, so the scaffold needs nothing installed beyond apicontract.
 */
import { type GeneratedFile } from './host.js';
import { type SampleFinding } from './lint-engine.js';
import { type Select } from './lint-select.js';

export const KINDS = ['generator', 'extractor', 'adapter', 'rules'] as const;

export type Kind = (typeof KINDS)[number];

const NAME = /^[a-z][\da-z]*(?:-[\da-z]+)*$/u;

/** Refuse a name that would not make a safe file name and a readable target name. */
export const checkName = (name: string): void => {
  if (!NAME.test(name)) {
    throw new Error(`"${name}" is not a plugin name. fix: use lowercase letters, digits and single dashes, starting with a letter, e.g. \`my-target\``);
  }
};

/** The one-operation OpenAPI document every scaffold's sample starts from. */
// eslint-disable-next-line secure-coding/no-graphql-injection -- TypeScript source text, not a GraphQL query; `name` passed `checkName`
const openapiSample = (name: string): string => `{
  openapi: '3.1.0',
  info: { title: '${name} sample', version: '1.0.0' },
  paths: { '/pets': { get: { operationId: 'listPets', responses: { '200': { description: 'the pets' } } } } },
}`;

const header = (name: string, kind: Kind, what: string): string => `/**
 * The \`${name}\` apicontract plugin: ${what}.
 *
 * Scaffolded by \`apicontract plugin new ${name} --kind ${kind}\`. ${kind === 'rules' ? 'Change `then` or `check`, then make `sample.findings`\n * say exactly what the rule finds on' : 'Change `run`, then make `sample`\n * say exactly what `run` returns for'} \`sample.document\`: \`node --test plugin-${name}.test.ts\` runs the
 * conformance suite and names every rule the plugin breaks, with a \`fix:\` line for each.
 */
`;

const generator = (name: string): string => `${header(name, 'generator', 'a generator, spec to code')}import { type Contract, type GeneratedFile, type Plugin } from 'apicontract/testing';

/** One file: the operation ids, sorted so two runs give the same bytes. */
const run = (contract: Contract): GeneratedFile[] => {
  const ids = contract.operations.map((operation) => operation.id).toSorted();
  return [{ path: '${name}.ts', owner: 'generated', content: \`// generated by ${name}: do not edit\\nexport const operations = \${JSON.stringify(ids)} as const;\\n\` }];
};

export const plugin: Plugin = {
  name: '${name}',
  generators: {
    '${name}': {
      description: 'The operation ids of a spec, as a TypeScript constant',
      inputs: ['openapi'],
      sample: {
        document: ${openapiSample(name).replaceAll('\n', '\n        ')},
        files: [{ path: '${name}.ts', owner: 'generated', content: '// generated by ${name}: do not edit\\nexport const operations = ["listPets"] as const;\\n' }],
      },
      run,
    },
  },
};
`;

const extractor = (name: string): string => `${header(name, 'extractor', 'an extractor, code to spec')}import { type Plugin } from 'apicontract/testing';

/** The operations named in \`options.operations\`; a real extractor reads them from the user's code instead. */
const run = (options: Readonly<Record<string, unknown>>): unknown => {
  const named = Array.isArray(options.operations) ? options.operations.filter((id): id is string => typeof id === 'string') : [];
  const paths = Object.fromEntries(named.toSorted().map((id) => [\`/\${id}\`, { get: { operationId: id, responses: { '200': { description: 'ok' } } } }]));
  return { openapi: '3.1.0', info: { title: '${name}', version: '0.0.0' }, paths };
};

export const plugin: Plugin = {
  name: '${name}',
  extractors: {
    '${name}': {
      description: 'An OpenAPI document from the operations it is told about',
      sample: {
        options: { operations: ['listPets'] },
        document: { openapi: '3.1.0', info: { title: '${name}', version: '0.0.0' }, paths: { '/listPets': { get: { operationId: 'listPets', responses: { '200': { description: 'ok' } } } } } },
      },
      run,
    },
  },
};
`;

const adapter = (name: string): string => `${header(name, 'adapter', 'an input format, and a generator that reads it')}import { type Contract, type GeneratedFile, type Plugin } from 'apicontract/testing';

/** A document in this format: \`{ "${name}": 1, "operations": ["listPets"] }\`. */
const detect = (document: unknown): boolean => typeof document === 'object' && document !== null && (document as Record<string, unknown>)['${name}'] === 1;

const read = (document: unknown): Contract => {
  const { operations } = document as { operations?: unknown };
  const ids = Array.isArray(operations) ? operations.filter((id): id is string => typeof id === 'string') : [];
  return { format: '${name}', document, operations: ids.map((id, index) => ({ id, source: \`#/operations/\${String(index)}\`, payloads: [] })) };
};

/** The generator that shows the format reads: the operation ids, sorted. */
const run = (contract: Contract): GeneratedFile[] => [
  { path: 'operations.txt', owner: 'generated', content: contract.operations.map((operation) => \`\${operation.id}\\n\`).toSorted().join('') },
];

export const plugin: Plugin = {
  name: '${name}',
  adapters: { '${name}': { description: 'The ${name} format', detect, read } },
  generators: {
    '${name}-operations': {
      description: 'The operation ids of a ${name} document, one per line',
      inputs: ['${name}'],
      sample: { document: { '${name}': 1, operations: ['listPets'] }, files: [{ path: 'operations.txt', owner: 'generated', content: 'listPets\\n' }] },
      run,
    },
  },
};

/** The sample after a spec change, for the conformance suite's regeneration rule: it can only change OpenAPI itself. */
export const mutate = (document: unknown): unknown => ({ ...(document as object), operations: ['listPets', 'createPet'] });
`;

/** A rule seeded from one finding (apicontract-lint R7): the document it was found in, and where. */
export interface RuleSeed {
  readonly document: unknown;
  readonly select: Select;
  readonly pointer: string;
  readonly message: string;
  readonly fix: string;
  /** What the seeded rule finds on `document`: its sample. */
  readonly findings: readonly SampleFinding[];
}

/** How deep a seeded rule's sample sits: plugin, rules, the rule, sample. */
const SAMPLE_DEPTH = 4;

/** A value as TypeScript source, indented to sit `depth` levels in. */
const literal = (value: unknown, depth: number): string => JSON.stringify(value, undefined, 2).replaceAll('\n', `\n${'  '.repeat(depth)}`);

const rule = (name: string): string => `${header(name, 'rules', '`lint` rules')}import { type Plugin } from 'apicontract/testing';

export const plugin: Plugin = {
  name: '${name}',
  rules: {
    '${name}': {
      description: 'Every operation has a summary',
      given: { select: 'operation' },
      then: { field: 'summary', function: 'truthy' },
      fix: 'add a one-line \`summary\` saying what the operation does',
      sample: {
        document: ${openapiSample(name).replaceAll('\n', '\n        ')},
        findings: [{ pointer: '#/paths/~1pets/get', message: '\`summary\` is missing' }],
      },
    },
  },
};
`;

/** A rule that finds the one mistake a finding named: a start, to widen into the mistake in general. */
const seeded = (name: string, seed: RuleSeed): string => `${header(name, 'rules', '`lint` rules')}import { type Plugin } from 'apicontract/testing';

// Seeded from one finding: \`check\` flags exactly the node it was found at. Widen it to say what makes
// any node this mistake, then add the documents it should and should not flag to \`sample\`.
const DOCUMENT = ${literal(seed.document, 0)};

export const plugin: Plugin = {
  name: '${name}',
  rules: {
    '${name}': {
      description: ${JSON.stringify(`Never again: ${seed.message}`)},
      given: { select: '${seed.select}' },
      check: (node) => (node.pointer === ${JSON.stringify(seed.pointer)} ? [${JSON.stringify(seed.message)}] : []),
      fix: ${JSON.stringify(seed.fix)},
      sample: {
        document: DOCUMENT,
        findings: ${literal(seed.findings, SAMPLE_DEPTH)},
      },
    },
  },
};
`;

const test = (name: string, kind: Kind): string => `import { test } from 'node:test';

import { conformance } from 'apicontract/testing';

import { ${kind === 'adapter' ? 'mutate, plugin' : 'plugin'} } from './plugin-${name}.js';

test('the ${name} plugin passes the apicontract conformance suite', async () => {
  await conformance(plugin${kind === 'adapter' ? ', { mutate }' : ''});
});
`;

const readme = (name: string, kind: Kind): string => `# ${name}

An [apicontract](https://github.com/ofri-peretz/burgee/tree/main/packages/apicontract) plugin: a
${kind}, scaffolded by \`apicontract plugin new ${name} --kind ${kind}\`.

## Check it

\`\`\`sh
node --test plugin-${name}.test.ts
\`\`\`

The test runs the conformance suite from \`apicontract/testing\`. It passes as scaffolded, and it
names every rule a change breaks, each with a \`fix:\` line:

| Rule | What it asks |
|---|---|
| \`schema\` | \`validate\` accepts the plugin, and it contributes a generator, an extractor, an adapter or a rule |
| \`sample\` | \`run\` on \`sample.document\` returns exactly \`sample.files\` (an extractor: \`sample.document\`; a rule: \`sample.findings\`) |
| \`deterministic\` | two runs give the same bytes |
| \`regeneration\` | after a spec change, every \`owner: 'user'\` file is byte for byte what it was |
| \`roundtrip\` | with \`{ extractor }\`: extracting what the generator wrote gives back the sample contract |
| \`fix-lines\` | every refusal and every finding says what to do: \`fix: …\` |
| \`paths\` | every path stays inside the output folder, even for an operation id with \`../\` in it |
| \`no-io\` | a rule reads only the node and the contract it is given: it never calls \`fetch\` |

## Use it

The files are ES modules: keep them in a package with \`"type": "module"\`. Add the plugin to \`apicontract.config.json\`:

\`\`\`json
{ "plugins": ["./plugin-${name}.ts"] }
\`\`\`
`;

/** The scaffold's files for a plugin called `name`, every one of them the user's. */
export const scaffold = (name: string, kind: Kind, seed?: RuleSeed): GeneratedFile[] => {
  checkName(name);
  const templates = { generator, extractor, adapter, rules: rule };
  if (!(KINDS as readonly string[]).includes(kind)) throw new Error(`"${String(kind)}" is not a plugin kind. fix: pass --kind ${KINDS.join(', --kind ')}`);
  const source = seed === undefined ? templates[kind](name) : seeded(name, seed);
  return [
    { path: `plugin-${name}.ts`, owner: 'user', content: source },
    { path: `plugin-${name}.test.ts`, owner: 'user', content: test(name, kind) },
    { path: 'README.md', owner: 'user', content: readme(name, kind) },
  ];
};
