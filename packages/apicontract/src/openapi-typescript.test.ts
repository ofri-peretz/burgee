import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { Readable } from 'node:stream';
import { pathToFileURL } from 'node:url';

import { afterAll, describe, expect, it } from 'vitest';

import { generate } from './gen-ts-index.js';
import openapiTS, { astToString, COMMENT_HEADER, transformSchemaObject } from './openapi-typescript.js';

const document = { openapi: '3.1.0', components: { schemas: { Id: { type: 'string' } } } };
const yaml = 'openapi: 3.1.0\ncomponents:\n  schemas:\n    Id:\n      type: string\n';
const want = generate(document);

const dir = mkdtempSync(path.join(tmpdir(), 'apicontract-ots-'));
afterAll(() => {
  rmSync(dir, { recursive: true, force: true });
});

describe('the openapi-typescript drop-in', () => {
  it('carries the header openapi-typescript 7.13.0 writes, byte for byte', () => {
    expect(COMMENT_HEADER).toBe('/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n');
  });

  it('generates the types of a parsed document, and astToString hands the text back', async () => {
    const result = await openapiTS(document);
    expect(result).toContain('Id: string;');
    expect(result).toBe(want);
    expect(astToString(result)).toBe(want);
  });

  it('passes options through', async () => {
    expect(await openapiTS(document, { exportType: true })).toBe(generate(document, { exportType: true }));
  });

  it.each([
    ['YAML text', yaml],
    ['JSON text', JSON.stringify(document)],
    ['JSON text after blank lines', `\n  ${JSON.stringify(document)}`],
    ['a buffer of YAML', Buffer.from(yaml)],
    ['a stream of YAML', Readable.from([yaml.slice(0, 20), yaml.slice(20)])],
  ])('reads %s', async (_, source) => {
    expect(await openapiTS(source)).toBe(want);
  });

  it('reads a file: URL', async () => {
    const file = path.join(dir, 'api.yaml');
    writeFileSync(file, yaml);
    expect(await openapiTS(pathToFileURL(file))).toBe(want);
  });

  it.each([
    ['a remote URL', new URL('https://example.com/api.yaml'), '`https://example.com/api.yaml` is a remote address'],
    ['a remote address as text', 'http://example.com/api.yaml', '`http://example.com/api.yaml` is a remote address'],
  ])('refuses %s rather than fetching it', async (_, source, message) => {
    const failure = (await openapiTS(source).catch((cause: unknown) => cause)) as Error;
    expect(failure.message).toBe(`${message}, and this package does not fetch.\nfix: download the document and pass its text, its parsed value or a \`file:\` URL`);
  });

  it.each([undefined, null, ''])('refuses %j as an empty schema, with a fix', async (source) => {
    const failure = (await openapiTS(source as unknown as string).catch((cause: unknown) => cause)) as Error;
    expect(failure.message).toBe('Empty schema.\nfix: pass a document, its YAML or JSON text, or a `file:` URL');
  });

  it("exports the transforms upstream's entry exports", () => {
    expect(typeof transformSchemaObject).toBe('function');
  });
});
