import { createHash } from 'node:crypto';

import { describe, expect, it } from 'vitest';

import { digest, headerLine, readHeader, withHeader } from './run-header.js';

const NOTE = 'generated by apicontract — do not edit; run `apicontract gen`';

describe('digest', () => {
  it('is the first 12 hex digits of the sha256', () => {
    expect(digest('abc')).toBe(createHash('sha256').update('abc').digest('hex').slice(0, 12));
    expect(digest('abc')).toBe('ba7816bf8f01');
  });
});

describe('headerLine', () => {
  it.each(['ts', 'tsx', 'mts', 'cts', 'js', 'jsx', 'mjs', 'cjs'])('opens a .%s file with //', (ext) => {
    expect(headerLine(`a/b.${ext}`, 'abc', 'apicontract gen')).toBe(`// ${NOTE} (sha256:ba7816bf8f01)`);
  });

  it.each(['yaml', 'yml'])('opens a .%s file with #', (ext) => {
    expect(headerLine(`b.${ext}`, 'abc', 'apicontract gen')).toBe(`# ${NOTE} (sha256:ba7816bf8f01)`);
  });

  it('wraps a Markdown header in an HTML comment', () => {
    expect(headerLine('README.md', 'abc', 'apicontract gen')).toBe(`<!-- ${NOTE} (sha256:ba7816bf8f01) -->`);
  });

  it.each(['schema.json', 'Makefile', 'a.ts.json'])('gives %s no header: its language has no comments, or it is unknown', (path) => {
    expect(headerLine(path, 'abc', 'apicontract gen')).toBeUndefined();
  });

  it('names the command it is given', () => {
    expect(headerLine('a.ts', 'abc', 'apicontract extract')).toContain('run `apicontract extract`');
  });
});

describe('withHeader and readHeader', () => {
  it('puts the header on its own line above the body, and reads both back', () => {
    const written = withHeader('a.ts', 'export type A = 1;\n', 'apicontract gen');
    expect(written).toBe(`// ${NOTE} (sha256:${digest('export type A = 1;\n')})\nexport type A = 1;\n`);
    expect(readHeader(written)).toEqual({ hash: digest('export type A = 1;\n'), body: 'export type A = 1;\n' });
  });

  it.each(['a.yaml', 'a.md'])('reads back the header it writes for %s', (path) => {
    expect(readHeader(withHeader(path, 'x\n', 'apicontract gen'))).toEqual({ hash: digest('x\n'), body: 'x\n' });
  });

  it('writes a file without comments as its body alone', () => {
    expect(withHeader('a.json', '{}\n', 'apicontract gen')).toBe('{}\n');
    expect(readHeader('{}\n')).toBeUndefined();
  });

  it.each([
    ['no header', 'export {};\n'],
    ['a header that is not the first line', `\n// ${NOTE} (sha256:ba7816bf8f01)\n`],
    ['a header with no newline after it', `// ${NOTE} (sha256:ba7816bf8f01)`],
    ['a short hash', `// ${NOTE} (sha256:ba7816bf8f0)\n`],
    ['a hash that is not hex', `// ${NOTE} (sha256:ba7816bf8f0g)\n`],
    ['an upper-case hash', `// ${NOTE} (sha256:BA7816BF8F01)\n`],
    ['text after the hash', `// ${NOTE} (sha256:ba7816bf8f01) edited\n`],
    ['text before the comment', `x// ${NOTE} (sha256:ba7816bf8f01)\n`],
    ['a command with a newline in it', '// generated by apicontract — do not edit; run `a\nb` (sha256:ba7816bf8f01)\n'],
    ['an empty command', '// generated by apicontract — do not edit; run `` (sha256:ba7816bf8f01)\n'],
    ['another comment marker', `-- ${NOTE} (sha256:ba7816bf8f01)\n`],
  ])('finds no header in a file with %s', (_, content) => {
    expect(readHeader(content)).toBeUndefined();
  });

  it('finds the header whatever command it names', () => {
    expect(readHeader(`# generated by apicontract — do not edit; run \`apicontract extract\` (sha256:ba7816bf8f01)\nabc`)).toEqual({ hash: 'ba7816bf8f01', body: 'abc' });
  });
});
